"use client";

import React, { useState } from "react";
import { 
  FileSpreadsheet, 
  UploadCloud, 
  KeyRound, 
  CheckCircle2, 
  AlertTriangle, 
  Download, 
  Sparkles, 
  Building2, 
  Check, 
  ArrowRight,
  RefreshCw,
  Search,
  Filter,
  FileCode,
  ShieldCheck
} from "lucide-react";
import { formatCurrencyINR, formatDate } from "@/lib/utils";
import { useTaxoData } from "@/lib/hooks/useTaxoData";
import { toast } from "@/components/shared/ToastNotification";

export interface ParsedTransaction {
  id: string;
  date: string;
  narration: string;
  chqRefNo: string;
  withdrawal: number;
  deposit: number;
  balance: number;
  suggestedLedger: string;
  confidence: number;
  status: "MAPPED" | "SUSPENSE" | "CONFIRMED";
}

const SAMPLE_TRANSACTIONS: ParsedTransaction[] = [];

export const BankStatementParser: React.FC = () => {
  const { clients } = useTaxoData();
  const [selectedEntityId, setSelectedEntityId] = useState<string>("");
  const [selectedBank, setSelectedBank] = useState<string>("HDFC_BANK");
  const [passwordMode, setPasswordMode] = useState<"AUTO_PAN" | "MANUAL">("AUTO_PAN");
  const [manualPassword, setManualPassword] = useState<string>("");
  const [transactions, setTransactions] = useState<ParsedTransaction[]>(SAMPLE_TRANSACTIONS);
  const [isProcessing, setIsProcessing] = useState<boolean>(false);
  const [exportNotice, setExportNotice] = useState<string | null>(null);
  const [selectedLedgerFilter, setSelectedLedgerFilter] = useState<string>("ALL");

  const currentEntity = (clients && clients.length > 0)
    ? (clients.find(c => c.id === selectedEntityId) || clients[0])
    : null;

  const handleSimulateUpload = () => {
    setIsProcessing(true);
    setTimeout(() => {
      setIsProcessing(false);
      toast.success(
        "Bank Statement Parsed",
        "7 transactions extracted: 6 auto-mapped to ledgers, 1 flagged for Suspense review."
      );
      setExportNotice("Statement parsed: 7 transactions extracted, 6 auto-mapped to ledgers, 1 flagged for Suspense review.");
      setTimeout(() => setExportNotice(null), 6000);
    }, 1200);
  };

  const handleResolveSuspense = (txnId: string, newLedger: string) => {
    setTransactions(prev => prev.map(t => {
      if (t.id === txnId) {
        return {
          ...t,
          suggestedLedger: newLedger,
          confidence: 100,
          status: "CONFIRMED"
        };
      }
      return t;
    }));
    toast.success("Suspense Resolved", `Transaction mapped to ${newLedger}.`);
  };

  const generateTallyXml = () => {
    const xmlHeader = `<?xml version="1.0" encoding="utf-8"?>
<ENVELOPE>
  <HEADER>
    <TALLYREQUEST>Import Data</TALLYREQUEST>
  </HEADER>
  <BODY>
    <IMPORTDATA>
      <REQUESTDESC>
        <REPORTNAME>Vouchers</REPORTNAME>
      </REQUESTDESC>
      <REQUESTDATA>
        <!-- Generated by Brains & Taxes Enterprise Engine for ${currentEntity?.name || "Client Entity"} -->`;

    const vouchersXml = transactions.map(t => {
      const isPayment = t.withdrawal > 0;
      const amount = isPayment ? t.withdrawal : t.deposit;
      const voucherType = isPayment ? "Payment" : "Receipt";

      return `
        <TALLYMESSAGE xmlns:UDF="TallyUDF">
          <VOUCHER VCHTYPE="${voucherType}" ACTION="Create">
            <DATE>${t.date.replace(/-/g, "")}</DATE>
            <NARRATION>${t.narration} (Ref: ${t.chqRefNo})</NARRATION>
            <VOUCHERTYPENAME>${voucherType}</VOUCHERTYPENAME>
            <ALLLEDGERENTRIES.LIST>
              <LEDGERNAME>${t.suggestedLedger}</LEDGERNAME>
              <ISDEEMEDPOSITIVE>${isPayment ? "Yes" : "No"}</ISDEEMEDPOSITIVE>
              <AMOUNT>${isPayment ? -amount : amount}</AMOUNT>
            </ALLLEDGERENTRIES.LIST>
            <ALLLEDGERENTRIES.LIST>
              <LEDGERNAME>${selectedBank.replace(/_/g, " ")} Current A/c</LEDGERNAME>
              <ISDEEMEDPOSITIVE>${isPayment ? "No" : "Yes"}</ISDEEMEDPOSITIVE>
              <AMOUNT>${isPayment ? amount : -amount}</AMOUNT>
            </ALLLEDGERENTRIES.LIST>
          </VOUCHER>
        </TALLYMESSAGE>`;
    }).join("");

    const xmlFooter = `
      </REQUESTDATA>
    </IMPORTDATA>
  </BODY>
</ENVELOPE>`;

    return `${xmlHeader}${vouchersXml}${xmlFooter}`;
  };

  const handleDownloadTallyXml = () => {
    const xmlContent = generateTallyXml();
    const blob = new Blob([xmlContent], { type: "application/xml" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${(currentEntity?.name || "Client").replace(/[^a-zA-Z0-9]/g, "_")}_Tally_Prime_Import.xml`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    toast.success("Tally Prime XML Exported", "XML vouchers generated. Import directly into Tally Prime.");
    setExportNotice("Tally Prime XML file generated! Open Tally Prime -> Import -> Transactions to load all entries.");
    setTimeout(() => setExportNotice(null), 6000);
  };

  const handleDownloadCsv = () => {
    const headers = "Date,Narration,Cheque Ref,Withdrawal (Dr),Deposit (Cr),Balance,Mapped Ledger,Status\n";
    const rows = transactions.map(t => 
      `"${t.date}","${t.narration}","${t.chqRefNo}",${t.withdrawal},${t.deposit},${t.balance},"${t.suggestedLedger}","${t.status}"`
    ).join("\n");
    const blob = new Blob([headers + rows], { type: "text/csv" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${(currentEntity?.name || "Client").replace(/[^a-zA-Z0-9]/g, "_")}_Bank_Audit_Ledger.csv`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    toast.success("CSV Exported", "Bank Audit Ledger CSV downloaded.");
  };

  const filteredTransactions = transactions.filter(t => {
    if (selectedLedgerFilter === "SUSPENSE") return t.status === "SUSPENSE";
    if (selectedLedgerFilter === "CONFIRMED") return t.status === "CONFIRMED";
    return true;
  });

  return (
    <div className="space-y-6 animate-fadeIn">
      {/* Top Banner */}
      <div className="bg-white border border-slate-200 rounded-3xl p-5 sm:p-6 shadow-sm flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="px-3 py-1 bg-emerald-50 border border-emerald-200 text-emerald-700 text-xs font-bold rounded-full flex items-center gap-1.5">
              <Sparkles className="w-3.5 h-3.5" /> 1-Click Bank OCR to Tally Prime
            </span>
            <span className="text-xs text-slate-500 font-medium">Saves 3+ hours per client per month</span>
          </div>
          <h2 className="text-2xl font-black text-slate-900 tracking-tight flex items-center gap-2">
            Bank Statement OCR &amp; Tally XML Generator
          </h2>
          <p className="text-sm text-slate-600 mt-0.5">
            Auto-decrypt password-protected bank PDFs, map narrations to standard ledgers, and export directly into Tally XML without manual typing.
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-3">
          <div className="flex items-center gap-2 bg-slate-50 border border-slate-200 rounded-2xl px-3 py-1.5">
            <Building2 className="w-4 h-4 text-slate-500" />
            <select
              value={selectedEntityId || currentEntity?.id || ""}
              onChange={(e) => setSelectedEntityId(e.target.value)}
              className="bg-transparent text-sm font-semibold text-slate-800 outline-none cursor-pointer"
            >
              {clients.length === 0 ? (
                <option value="">No clients onboarded</option>
              ) : (
                clients.map((c) => (
                  <option key={c.id} value={c.id}>
                    {c.name} ({c.type})
                  </option>
                ))
              )}
            </select>
          </div>
        </div>
      </div>

      {exportNotice && (
        <div className="p-4 bg-emerald-50 border border-emerald-200 rounded-2xl flex items-center justify-between text-emerald-800 text-sm font-medium animate-fadeIn">
          <div className="flex items-center gap-2">
            <CheckCircle2 className="w-5 h-5 text-emerald-600 shrink-0" />
            <span>{exportNotice}</span>
          </div>
          <button onClick={() => setExportNotice(null)} className="text-emerald-700 hover:underline text-xs font-bold">
            Dismiss
          </button>
        </div>
      )}

      {/* Parser Configuration Bar */}
      <div className="bg-white border border-slate-200 rounded-3xl p-5 shadow-sm grid grid-cols-1 md:grid-cols-4 gap-4 items-end">
        <div>
          <label className="text-xs font-bold text-slate-600 uppercase tracking-wider block mb-1">
            Bank Format Engine
          </label>
          <select
            value={selectedBank}
            onChange={(e) => setSelectedBank(e.target.value)}
            className="w-full bg-slate-50 border border-slate-200 rounded-xl p-2.5 text-xs font-bold text-slate-800 outline-none"
          >
            <option value="HDFC_BANK">HDFC Bank (Corporate NetBanking)</option>
            <option value="ICICI_BANK">ICICI Bank (CIB / RoC Format)</option>
            <option value="SBI_BANK">State Bank of India (INB Current A/c)</option>
            <option value="AXIS_BANK">Axis Bank (Corporate Statement)</option>
            <option value="KOTAK_BANK">Kotak Mahindra Bank</option>
            <option value="PNB_BANK">Punjab National Bank</option>
          </select>
        </div>

        <div>
          <label className="text-xs font-bold text-slate-600 uppercase tracking-wider block mb-1">
            Decryption Pattern
          </label>
          <select
            value={passwordMode}
            onChange={(e) => setPasswordMode(e.target.value as any)}
            className="w-full bg-slate-50 border border-slate-200 rounded-xl p-2.5 text-xs font-bold text-slate-800 outline-none"
          >
            <option value="AUTO_PAN">
              {currentEntity?.pan ? `Auto: Client PAN (${currentEntity.pan})` : "Auto: Client PAN (No Client Selected)"}
            </option>
            <option value="MANUAL">Custom Password Override</option>
          </select>
        </div>

        {passwordMode === "MANUAL" && (
          <div>
            <label className="text-xs font-bold text-slate-600 uppercase tracking-wider block mb-1">
              Enter Password
            </label>
            <input
              type="text"
              value={manualPassword}
              onChange={(e) => setManualPassword(e.target.value)}
              placeholder="e.g. Incorp Year or Customer ID"
              className="w-full bg-slate-50 border border-slate-200 rounded-xl p-2.5 text-xs font-bold text-slate-800 outline-none"
            />
          </div>
        )}

        <div className="flex gap-2">
          <button
            onClick={handleSimulateUpload}
            disabled={isProcessing}
            className="flex-1 px-4 py-2.5 bg-slate-900 hover:bg-black text-white text-xs font-bold rounded-xl flex items-center justify-center gap-2 transition disabled:opacity-60"
          >
            {isProcessing ? (
              <>
                <RefreshCw className="w-3.5 h-3.5 animate-spin" />
                Parsing Statement...
              </>
            ) : (
              <>
                <UploadCloud className="w-3.5 h-3.5" />
                Upload &amp; Auto-Parse
              </>
            )}
          </button>
        </div>
      </div>

      {/* Transaction Table & Actions */}
      <div className="bg-white border border-slate-200 rounded-3xl p-5 shadow-sm space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-200">
          <div className="flex items-center gap-3">
            <h3 className="text-base font-bold text-slate-900 flex items-center gap-2">
              <FileSpreadsheet className="w-4 h-4 text-emerald-600" />
              Extracted Transactions ({filteredTransactions.length})
            </h3>
            <div className="flex items-center gap-1 bg-slate-100 p-1 rounded-xl text-xs font-bold text-slate-600">
              <button
                onClick={() => setSelectedLedgerFilter("ALL")}
                className={`px-2.5 py-1 rounded-lg ${selectedLedgerFilter === "ALL" ? "bg-white text-slate-900 shadow-sm" : ""}`}
              >
                All
              </button>
              <button
                onClick={() => setSelectedLedgerFilter("SUSPENSE")}
                className={`px-2.5 py-1 rounded-lg ${selectedLedgerFilter === "SUSPENSE" ? "bg-rose-50 text-rose-700 shadow-sm" : ""}`}
              >
                Suspense Review ({transactions.filter(t => t.status === "SUSPENSE").length})
              </button>
              <button
                onClick={() => setSelectedLedgerFilter("CONFIRMED")}
                className={`px-2.5 py-1 rounded-lg ${selectedLedgerFilter === "CONFIRMED" ? "bg-emerald-50 text-emerald-700 shadow-sm" : ""}`}
              >
                Mapped ({transactions.filter(t => t.status === "CONFIRMED").length})
              </button>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleDownloadCsv}
              className="px-3.5 py-1.5 bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-bold rounded-xl flex items-center gap-1.5 transition"
            >
              <Download className="w-3.5 h-3.5" /> Export Excel
            </button>
            <button
              onClick={handleDownloadTallyXml}
              className="px-4 py-1.5 bg-emerald-600 hover:bg-emerald-700 text-white text-xs font-bold rounded-xl flex items-center gap-1.5 shadow-sm transition"
            >
              <FileCode className="w-3.5 h-3.5" /> Export Tally Prime XML
            </button>
          </div>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead>
              <tr className="border-b border-slate-200 text-slate-500 font-bold uppercase tracking-wider bg-slate-50/60">
                <th className="p-3">Date &amp; Ref</th>
                <th className="p-3">Bank Narration</th>
                <th className="p-3 text-right">Debit (Dr)</th>
                <th className="p-3 text-right">Credit (Cr)</th>
                <th className="p-3">AI Suggested Ledger</th>
                <th className="p-3">Confidence</th>
                <th className="p-3 text-center">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {filteredTransactions.length === 0 ? (
                <tr>
                  <td colSpan={7} className="p-12 text-center text-slate-500">
                    <FileSpreadsheet className="w-8 h-8 text-slate-400 mx-auto mb-2" />
                    <div className="font-bold text-slate-800 text-sm">No Bank Transactions Parsed Yet</div>
                    <div className="text-xs text-slate-400 mt-1 max-w-md mx-auto">
                      Upload password-protected PDF bank statements or Excel exports above to automatically extract entries and generate Tally XML vouchers.
                    </div>
                  </td>
                </tr>
              ) : (
                filteredTransactions.map((t) => (
                <tr key={t.id} className="hover:bg-slate-50/80 transition">
                  <td className="p-3 whitespace-nowrap">
                    <div className="font-bold text-slate-900">{formatDate(t.date)}</div>
                    <div className="text-[10px] text-slate-400 font-mono">{t.chqRefNo}</div>
                  </td>
                  <td className="p-3 max-w-xs font-mono text-[11px] text-slate-700 break-words">
                    {t.narration}
                  </td>
                  <td className="p-3 text-right font-black text-rose-600 whitespace-nowrap">
                    {t.withdrawal > 0 ? formatCurrencyINR(t.withdrawal) : "—"}
                  </td>
                  <td className="p-3 text-right font-black text-emerald-600 whitespace-nowrap">
                    {t.deposit > 0 ? formatCurrencyINR(t.deposit) : "—"}
                  </td>
                  <td className="p-3">
                    {t.status === "SUSPENSE" ? (
                      <span className="px-2.5 py-1 bg-rose-50 border border-rose-200 text-rose-700 font-bold rounded-lg flex items-center gap-1 w-fit">
                        <AlertTriangle className="w-3 h-3 text-rose-500" /> {t.suggestedLedger}
                      </span>
                    ) : (
                      <span className="font-semibold text-slate-800">
                        {t.suggestedLedger}
                      </span>
                    )}
                  </td>
                  <td className="p-3">
                    <div className="flex items-center gap-1.5">
                      <div className="w-12 bg-slate-100 rounded-full h-1.5 overflow-hidden">
                        <div
                          className={`h-full ${t.confidence >= 90 ? "bg-emerald-500" : t.confidence >= 70 ? "bg-amber-500" : "bg-rose-500"}`}
                          style={{ width: `${t.confidence}%` }}
                        />
                      </div>
                      <span className="text-[10px] font-bold text-slate-500">{t.confidence}%</span>
                    </div>
                  </td>
                  <td className="p-3 text-center whitespace-nowrap">
                    {t.status === "SUSPENSE" ? (
                      <div className="flex items-center justify-center gap-1.5">
                        <button
                          onClick={() => handleResolveSuspense(t.id, "Sundry Debtors Ledger (Trade Receivables)")}
                          className="px-2 py-1 bg-indigo-50 hover:bg-indigo-100 text-indigo-700 font-bold rounded-lg text-[10px]"
                        >
                          Map to Debtor
                        </button>
                        <button
                          onClick={() => handleResolveSuspense(t.id, "Director Current A/c Capital Loan")}
                          className="px-2 py-1 bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold rounded-lg text-[10px]"
                        >
                          Map to Capital
                        </button>
                      </div>
                    ) : (
                      <span className="text-emerald-600 inline-flex items-center gap-1 text-[11px] font-bold">
                        <Check className="w-3.5 h-3.5" /> Ready
                      </span>
                    )}
                  </td>
                </tr>
              )))}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
