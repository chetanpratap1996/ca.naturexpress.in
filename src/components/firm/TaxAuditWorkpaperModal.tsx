interface TaxAuditWorkpaperModalProps {
  isOpen: boolean;
  onClose: () => void;
  entityName: string;
  onUdinSaved?: (udin: string) => void;
}

export const TaxAuditWorkpaperModal: React.FC<TaxAuditWorkpaperModalProps> = ({
  isOpen,
  onClose,
  entityName,
  onUdinSaved,
}) => {
  const [clauses, setClauses] = useState<ClauseItem[]>(INITIAL_CLAUSES);
  const [udinInput, setUdinInput] = useState<string>("24049281AAAAAA8912");
  const [recordedUdin, setRecordedUdin] = useState<string>("24049281AAAAAA8912");
  const [isSaving, setIsSaving] = useState(false);
  const [saveSuccess, setSaveSuccess] = useState(false);
  const [udinError, setUdinError] = useState<string | null>(null);

  if (!isOpen) return null;

  const totalDisallowances = clauses.reduce((sum, c) => sum + c.disallowanceAmount, 0);

  const handleTogglePartnerSign = (clauseId: string) => {
    setClauses((prev) =>
      prev.map((c) =>
        c.id === clauseId ? { ...c, partnerSignedOff: !c.partnerSignedOff } : c
      )
    );
  };

  /**
   * ICAI UDIN Format Validation:
   * Standard 18 characters alphanumeric:
   * First 2 digits: Year (e.g. 24, 25, 26)
   * Next 6 digits: CA Membership Number (e.g. 049281)
   * Next 10 chars: Alphanumeric document identifier generated by ICAI portal
   */
  const validateUdin = (value: string): boolean => {
    const cleaned = value.trim().toUpperCase();
    const udinRegex = /^[0-9]{2}[0-9]{6}[A-Z0-9]{10}$/;
    if (!cleaned) {
      setUdinError("Please enter the 18-digit UDIN generated from the ICAI portal");
      return false;
    }
    if (cleaned.length !== 18) {
      setUdinError(`UDIN must be exactly 18 characters (Currently: ${cleaned.length})`);
      return false;
    }
    if (!udinRegex.test(cleaned)) {
      setUdinError("Invalid ICAI UDIN format (Format: YY + 6-digit Member No + 10 alphanumeric chars)");
      return false;
    }
    setUdinError(null);
    return true;
  };

  const handleSaveAndSign = () => {
    if (!validateUdin(udinInput)) return;

    setIsSaving(true);
    setTimeout(() => {
      const finalUdin = udinInput.trim().toUpperCase();
      setClauses((prev) => prev.map((c) => ({ ...c, partnerSignedOff: true })));
      setRecordedUdin(finalUdin);
      setIsSaving(false);
      setSaveSuccess(true);
      if (onUdinSaved) {
        onUdinSaved(finalUdin);
      }
      setTimeout(() => setSaveSuccess(false), 4000);
    }, 600);
  };

  return (
    <div className="fixed inset-0 bg-black/60 backdrop-blur-sm z-50 flex items-center justify-center p-3 sm:p-4">
      <div className="bg-white rounded-3xl max-w-3xl w-full p-4 sm:p-6 shadow-2xl border border-slate-200 space-y-4 relative animate-in fade-in zoom-in-95 max-h-[90dvh] flex flex-col">
        <button
          onClick={onClose}
          className="absolute right-3.5 top-3.5 sm:right-4 sm:top-4 text-slate-400 hover:text-slate-800 p-1"
        >
          <X className="w-5 h-5" />
        </button>

        {/* Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-slate-200 pb-3 pr-8 sm:pr-0">
          <div>
            <div className="flex flex-wrap items-center gap-2">
              <span className="text-[10px] font-black uppercase px-2.5 py-0.5 rounded-full bg-red-100 text-btred-logo border border-red-200">
                ICAI Tax Audit Workpaper &bull; Form 3CA - 3CD
              </span>
              <span className="text-xs text-slate-500 font-semibold">AY 2026-27</span>
            </div>
            <h3 className="text-base sm:text-lg font-black text-slate-900 mt-1">{entityName}</h3>
            <p className="text-xs text-slate-500 font-medium">
              Maker: Kriti Jain (Article) &bull; Signatory: CA Gunjan Jain (GPA &amp; Co., FRN: 022998C)
            </p>
          </div>

          <div className="text-left sm:text-right bg-slate-50 p-2 sm:p-2.5 rounded-2xl border border-slate-200 self-start sm:self-auto">
            <span className="text-[10px] uppercase font-bold text-slate-500 block">Total Disallowances</span>
            <span className="text-base sm:text-lg font-black text-btred-logo">{formatCurrencyINR(totalDisallowances)}</span>
          </div>
        </div>

        {/* Clause Master Checklist */}
        <div className="space-y-3 overflow-y-auto flex-1 pr-1">
          {clauses.map((clause) => (
            <div
              key={clause.id}
              className="bg-slate-50 border border-slate-200 p-4 rounded-2xl space-y-2 text-xs"
            >
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-2">
                  <span className="font-black text-slate-900 text-xs bg-white border border-slate-200 px-2 py-0.5 rounded-lg">
                    {clause.clauseNo}
                  </span>
                  <span className="font-bold text-slate-900">{clause.title}</span>
                  <span className="text-[10px] text-slate-500 font-mono">({clause.actSection})</span>
                </div>

                <div className="flex items-center gap-2">
                  {clause.disallowanceAmount > 0 && (
                    <span className="bg-red-50 text-btred-logo font-black px-2 py-0.5 rounded text-[10px] border border-red-200">
                      Disallowance: {formatCurrencyINR(clause.disallowanceAmount)}
                    </span>
                  )}

                  <button
                    onClick={() => handleTogglePartnerSign(clause.id)}
                    className={`px-2.5 py-1 rounded-lg text-[10px] font-black transition flex items-center gap-1 ${
                      clause.partnerSignedOff
                        ? "bg-emerald-100 text-emerald-800 border border-emerald-300"
                        : "bg-slate-200 text-slate-700 hover:bg-slate-300"
                    }`}
                  >
                    {clause.partnerSignedOff ? (
                      <>
                        <Check className="w-3 h-3 text-emerald-600" /> Partner Sign-Off
                      </>
                    ) : (
                      "Sign Off Clause"
                    )}
                  </button>
                </div>
              </div>

              <p className="text-[11px] text-slate-700 bg-white p-2.5 rounded-xl border border-slate-100 font-medium">
                {clause.findingNote}
              </p>

              <div className="flex items-center justify-between text-[10px] text-slate-500">
                <span className="text-emerald-700 font-bold">✓ Article Verified (Ledgers &amp; Sample Vouchers Attached)</span>
                <span className="font-bold text-slate-600">{clause.penaltyRiskNote}</span>
              </div>
            </div>
          ))}
        </div>

        {/* ICAI Compliant UDIN Recording Section */}
        <div className="pt-3 border-t border-slate-200 space-y-3">
          <div className="bg-slate-50 border border-slate-200 rounded-2xl p-3.5 space-y-2">
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-2">
                <ShieldCheck className="w-4 h-4 text-emerald-600" />
                <span className="text-xs font-black text-slate-900">
                  Official ICAI UDIN Linkage &amp; Stamping
                </span>
              </div>
              <a
                href="https://udin.icai.org"
                target="_blank"
                rel="noreferrer"
                className="text-[11px] text-btred-logo font-bold hover:underline flex items-center gap-1"
              >
                <span>Generate on udin.icai.org</span>
                <ExternalLink className="w-3 h-3" />
              </a>
            </div>

            <p className="text-[11px] text-slate-500">
              Per ICAI mandate, UDIN must be generated directly by the signing Chartered Accountant on the ICAI portal. Record the official 18-digit UDIN below to stamp it onto the certified workpaper audit trail.
            </p>

            <div className="flex flex-col sm:flex-row items-stretch sm:items-center gap-2 pt-1">
              <div className="flex-1">
                <input
                  type="text"
                  maxLength={18}
                  placeholder="Enter 18-digit UDIN (e.g., 24049281AAAAAA8912)"
                  value={udinInput}
                  onChange={(e) => {
                    setUdinInput(e.target.value.toUpperCase());
                    if (udinError) setUdinError(null);
                  }}
                  className="w-full bg-white border border-slate-300 font-mono text-xs px-3 py-2 rounded-xl text-slate-900 uppercase tracking-wider focus:outline-none focus:border-slate-800"
                />
                {udinError && (
                  <p className="text-[11px] text-red-600 font-bold mt-1 flex items-center gap-1">
                    <AlertCircle className="w-3 h-3" /> {udinError}
                  </p>
                )}
              </div>

              <button
                onClick={handleSaveAndSign}
                disabled={isSaving}
                className="bg-btblack hover:bg-slate-800 text-white text-xs font-black px-4 py-2 rounded-xl transition shadow flex items-center justify-center gap-1.5 shrink-0"
              >
                {isSaving ? (
                  <>
                    <div className="w-3 h-3 border-2 border-white border-t-transparent rounded-full animate-spin"></div>
                    Recording UDIN...
                  </>
                ) : (
                  <>
                    <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
                    Record UDIN &amp; Partner Sign-Off
                  </>
                )}
              </button>
            </div>

            {saveSuccess && (
              <div className="bg-emerald-50 border border-emerald-300 text-emerald-800 text-xs font-bold p-2.5 rounded-xl flex items-center gap-2">
                <Check className="w-4 h-4 text-emerald-600" />
                <span>Official UDIN <strong>{recordedUdin}</strong> recorded and stamped on Form 3CD workpaper!</span>
              </div>
            )}
          </div>

          <div className="flex items-center justify-between text-xs text-slate-500 pt-1">
            <span>
              Stamped UDIN: <strong className="font-mono text-slate-900">{recordedUdin || "Pending"}</strong>
            </span>
            <button
              onClick={onClose}
              className="px-4 py-1.5 text-xs font-bold text-slate-600 hover:text-slate-900 border border-slate-200 rounded-xl"
            >
              Close Workpaper
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
