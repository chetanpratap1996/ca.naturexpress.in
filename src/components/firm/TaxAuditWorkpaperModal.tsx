import React, { useState } from "react";
import { 
  X, 
  Check, 
  ExternalLink,
  ShieldCheck, 
  FileText, 
  AlertCircle,
  CheckCircle2
} from "lucide-react";
import { formatCurrencyINR } from "@/lib/utils";

